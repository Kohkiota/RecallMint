// ============================================================================
// プロンプト組み立て
// ============================================================================
export function buildPrompt(propertySchema: PropertySchema): string {
  return [
    COMMON_EXTRACTION_RULES,
    EXPLANATION_USAGE_RULES,
    buildSchemaCustomPropsRules(propertySchema),
    STRUCTURE_PRESERVATION_RULES,
    SHARED_CONTEXT_RULES,
    IMAGE_REFERENCE_RULES,
    ANSWER_GROUNDING_RULES,
  ].join("\n\n");
}

