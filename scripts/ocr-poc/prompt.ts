// ============================================================================
// schema mode 用 custom_props ルール
// ============================================================================
function buildSchemaCustomPropsRules(propertySchema: PropertySchema): string {
  const propsHint = propertySchema
    .slice()
    .sort((a, b) => a.display_order - b.display_order)
    .map((d) => {
      const opts = d.select_options?.length
        ? ` (選択肢: ${d.select_options.join(", ")})`
        : "";
      return `  - ${d.name} [${d.type}]${opts}`;
    })
    .join("\n");

  return [
    "【custom_props (optional)】",
    "",
    "以下のプロパティが文書上で **明示的に読み取れる場合のみ** 埋めてください:",
    propsHint || "  (定義なし → 省略可)",
    "",
    "- single_select / multi_select は select_options のいずれかに正規化",
    "- 該当値が読み取れないキーは省略 (null や空文字を入れない)",
    "- 全キーとも読み取れない問題は custom_props 自体を出力しなくてよい",
    "  (required から外してある。推測で埋めず、出力を省略する選択を優先)",
  ].join("\n");
}

